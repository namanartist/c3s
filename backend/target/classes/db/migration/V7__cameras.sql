-- V7__cameras.sql: CCTV Nodes & Heartbeats
CREATE TABLE IF NOT EXISTS cameras (
    id UUID PRIMARY KEY,
    camera_code VARCHAR(50) NOT NULL UNIQUE,
    name VARCHAR(255) NOT NULL,
    gate_id UUID REFERENCES gates(id),
    building VARCHAR(100),
    zone VARCHAR(100) NOT NULL,
    latitude DOUBLE PRECISION NOT NULL,
    longitude DOUBLE PRECISION NOT NULL,
    status VARCHAR(50) NOT NULL DEFAULT 'ONLINE', -- ONLINE, OFFLINE, DEGRADED, MAINTENANCE, UNKNOWN
    stream_reference VARCHAR(255),
    ip_address VARCHAR(50),
    resolution VARCHAR(50) DEFAULT '1080p',
    fps INT DEFAULT 30,
    ptz_capable BOOLEAN DEFAULT FALSE,
    last_heartbeat TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS camera_events (
    id UUID PRIMARY KEY,
    camera_id UUID NOT NULL REFERENCES cameras(id) ON DELETE CASCADE,
    event_type VARCHAR(100) NOT NULL, -- MOTION_DETECTED, SIGNAL_LOST, SIGNAL_RESTORED, TRIPWIRE_TRIGGERED
    detail TEXT,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP
);